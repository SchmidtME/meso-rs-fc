within = table(...
    repmat({'A'; 'B'; 'C'}, 26, 1), ... % effect of layer
    repmat({'AA'; 'AA'; 'AA'; 'BB'; 'BB'; 'BB'; 'CC'; 'CC'; 'CC'; ...
    'DD'; 'DD'; 'DD'; 'EE'; 'EE'; 'EE'; 'FF'; 'FF'; 'FF'; ...
    'GG'; 'GG'; 'GG'; 'HH'; 'HH'; 'HH'; 'II'; 'II'; 'II'; ...
    'JJ'; 'JJ'; 'JJ'; 'KK'; 'KK'; 'KK'; 'LL'; 'LL'; 'LL'; ...
    'MM'; 'MM'; 'MM'}, 2, 1), ... % effect of donut radius
    [repmat({'AAA'}, 39, 1); repmat({'BBB'}, 39, 1)], ... % effect of measurement type
    'VariableNames', {'Layer', 'Radius', 'Type'});

rm = fitrm(t,'t1-t78~1','WithinDesign',within)
disp('Comparison radius & layer & type for shifted H0')
ranovatbl = ranova(rm,'WithinModel','Layer+Radius+Type+Layer*Type+Layer*Radius+Radius*Layer+Radius*Type+Radius*Type*Layer')

