layers = {'0-2', '4-6', '8-10'};

%% Load data (shifted version)

% Initialize cell array to store meanAbsR for each subject
meanAbsRAll = zeros(length(subNames),length(layers),length(distEdgeRange),2,2);

for n = 1:length(subNames)
    for l = 1:length(layers)
        subjectDir = fullfile(baseDirectory, ['V1_layers_' layers{l} '_intrahemispheric'], subNames{n});
        matFilePath = fullfile(subjectDir, 'meanAbsR_Denoised_excl_3mm.mat');
        data = load(matFilePath, 'meanAbsR');
        meanAbsRAll(n,l,:,:,:) = data.meanAbsR;
    end
end

%% ANOVA (for shifted version)

% meanAbsRAll size: subjects, layers, distances, H1 H0, hemis
% mean over hemis
meanAbsRAll_mean = mean(meanAbsRAll,5);

