  meanAbsRAll_mean(:,1,12,1) meanAbsRAll_mean(:,2,12,1) meanAbsRAll_mean(:,1,12,1) ...
  meanAbsRAll_mean(:,1,13,1) meanAbsRAll_mean(:,2,13,1) meanAbsRAll_mean(:,1,13,1) ...
  meanAbsRAll_mean(:,1,1,2) meanAbsRAll_mean(:,2,1,2) meanAbsRAll_mean(:,1,1,2) ...
  meanAbsRAll_mean(:,1,2,2) meanAbsRAll_mean(:,2,2,2) meanAbsRAll_mean(:,1,2,2) ...
  meanAbsRAll_mean(:,1,3,2) meanAbsRAll_mean(:,2,3,2) meanAbsRAll_mean(:,1,3,2) ...
  meanAbsRAll_mean(:,1,4,2) meanAbsRAll_mean(:,2,4,2) meanAbsRAll_mean(:,1,4,2) ...
